"""
user.py — the User table.

A User owns Projects and authors Comments, and can be assigned Tasks.
This model also stores the *hashed* password — never the plaintext.
"""

from __future__ import annotations  # lets us reference "Project"/"Task" in type

import uuid
from typing import TYPE_CHECKING

from sqlalchemy import String
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.models.base import Base, TimestampMixin

# TYPE_CHECKING is True only for type checkers (mypy), never at runtime. We
# import related models here PURELY for the type annotations on relationships,
# without creating real circular imports at runtime. This is the standard trick
# for typing SQLAlchemy relationships between mutually-referencing models.
if TYPE_CHECKING:
    from src.models.comment import Comment
    from src.models.project import Project
    from src.models.task import Task


def _uuid_str() -> str:
    """Generate a random UUID as a string.

    WHY UUID PRIMARY KEYS INSTEAD OF AUTO-INCREMENT INTEGERS:
      - IDs are generated by the APP, so we know an object's id before the DB
        round-trip, and IDs don't collide when merging data from multiple
        sources.
      - They don't leak business info (an integer id=42 tells an attacker you
        have ~42 users; a UUID reveals nothing and isn't guessable/enumerable).
    We store the UUID as a 36-char string for maximum portability across SQLite
    and Postgres. (On Postgres you could use a native UUID column; string keeps
    the code identical on both, which serves this project's goals.)
    """
    return str(uuid.uuid4())


class User(Base, TimestampMixin):
    # __tablename__ is the actual table name in the database.
    __tablename__ = "users"

    # PRIMARY KEY. default=_uuid_str runs in Python at insert time to fill the id.
    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=_uuid_str
    )

    # Login identity. unique=True adds a UNIQUE constraint so two users can't
    # share an email. index=True builds a DB index so lookups by email (which we
    # do on every login) are fast rather than full-table scans.
    email: Mapped[str] = mapped_column(
        String(255), unique=True, index=True, nullable=False
    )

    # A human-friendly display name.
    full_name: Mapped[str] = mapped_column(String(120), nullable=False)

    # The BCRYPT HASH of the password — NEVER the plaintext. If our DB leaks,
    # attackers get hashes they must brute-force, not usable passwords. The name
    # makes it obvious this is not a plaintext field.
    hashed_password: Mapped[str] = mapped_column(String(255), nullable=False)

    # Soft on/off switch for an account without deleting it.
    is_active: Mapped[bool] = mapped_column(default=True, nullable=False)

    # ---- RELATIONSHIPS (Python-side navigation, no extra columns) ----
    # relationship() does NOT create a column; it teaches the ORM how to load
    # related rows so you can write user.projects instead of a manual query.
    #
    # back_populates wires BOTH sides together: Project.owner <-> User.projects
    # stay in sync in memory.
    #
    # cascade="all, delete-orphan": if a User is deleted, their Projects are
    # deleted too, and a Project removed from this list is deleted. Model this
    # deliberately — here, projects have no meaning without their owner.
    projects: Mapped[list["Project"]] = relationship(
        back_populates="owner",
        cascade="all, delete-orphan",
    )

    # Comments this user wrote.
    comments: Mapped[list["Comment"]] = relationship(back_populates="author")

    # Tasks assigned to this user. NOTE: foreign_keys is specified because Task
    # has TWO links to a person could exist; here assignee_id is the one we mean.
    assigned_tasks: Mapped[list["Task"]] = relationship(
        back_populates="assignee"
    )
